def main():
    assert len(FONT8X8_BASIC) == 96
    out = []
    out.append("// =============================================================================")
    out.append("// TD Engine - Embedded 8x16 bitmap font (UI toolkit)")
    out.append("//")
    out.append("// Source: font8x8 project (CC0 / public domain) by Daniel Hepper.")
    out.append("// Each 8x8 source glyph is doubled vertically to produce an 8x16 cell.")
    out.append("//")
    out.append("// Layout: 96 glyphs for ASCII [0x20 .. 0x7F]. Each glyph is 16 bytes, one")
    out.append("// per row, MSB = left-most pixel. Glyph index = (ascii_code - 32).")
    out.append("//")
    out.append("// This file is GENERATED by tools/gen_font.py -- do not hand-edit.")
    out.append("// =============================================================================")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace td {")
    out.append("")
    out.append("// 96 glyphs x 16 bytes/row = 1536 bytes.")
    out.append("static const unsigned char UI_FONT_DATA[96 * 16] = {")
    for gi, g in enumerate(FONT8X8_BASIC):
        rows16 = []
        for r in g:
            rows16.append(r)
            rows16.append(r)  # double vertically for 8x16
        assert len(rows16) == 16
        ascii_code = 0x20 + gi
        if 0x20 <= ascii_code < 0x7F:
            ch = chr(ascii_code)
            comment = f"  // 0x{ascii_code:02X} '{ch}'"
        else:
            comment = f"  // 0x{ascii_code:02X}"
        hex_vals = ",".join(f"0x{b:02X}" for b in rows16)
        out.append(f"    {hex_vals},{comment}")
    out.append("};")
    out.append("")
    out.append("// Glyph metrics. Each cell is 8 pixels wide, 16 pixels tall.")
    out.append("// A monospace advance of 8 px is used for layout; the renderer")
    out.append("// can scale the cell arbitrarily to achieve a target font size.")
    out.append("static constexpr int UI_FONT_GLYPH_W = 8;")
    out.append("static constexpr int UI_FONT_GLYPH_H = 16;")
    out.append("static constexpr int UI_FONT_GLYPH_COUNT = 96;")
    out.append("static constexpr int UI_FONT_FIRST_ASCII = 32;")
    out.append("")
    out.append("// Return the 16-byte bitmap for the given ASCII code, or the")
    out.append("// blank glyph if the code is out of range.")
    out.append("inline const unsigned char* uiFontGlyph(int asciiCode) {")
    out.append("    if (asciiCode < UI_FONT_FIRST_ASCII ||")
    out.append("        asciiCode >= UI_FONT_FIRST_ASCII + UI_FONT_GLYPH_COUNT) {")
    out.append("        return &UI_FONT_DATA[0];  // space glyph")
    out.append("    }")
    out.append("    return &UI_FONT_DATA[(asciiCode - UI_FONT_FIRST_ASCII) * 16];")
    out.append("}")
    out.append("")
    out.append("} // namespace td")
    out.append("")
    with open("src/ui/font_data.h", "w") as f:
        f.write("\n".join(out))
    print(f"Wrote src/ui/font_data.h ({96*16} bytes of glyph data)")

if __name__ == "__main__":
    main()
