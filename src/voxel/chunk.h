// =============================================================================
// TD Engine - Voxel Chunk System (Tier 2.3)
//
// Streaming voxel world for the Minecraft-style target. Inspired by Zylann's
// godot_voxel module and the Unity community pattern (SubScene streaming +
// Mesh.CombineMeshes).
//
// Architecture:
//   - The world is divided into fixed-size CUBIC chunks (default 16x16x16
//     voxels). Each chunk stores an array of block IDs (1 byte per block =
//     256 distinct block types, enough for Minecraft-like + modded content).
//   - Chunks are addressed by integer (cx, cy, cz) coordinates. A ChunkMap
//     holds the live chunks in a hash table keyed by packed (cx,cy,cz).
//   - A ChunkStreamer manages load/unload around a "focus point" (usually
//     the player). Chunks outside the render distance are unloaded; chunks
//     inside are loaded from disk (or generated by a TerrainGenerator on
//     first encounter).
//   - A ChunkMesher turns the voxel array into a renderable mesh. The
//     default mesher is "naive" (one quad per visible block face); a
//     greedy mesher is TODO (Tier 3.8).
//
// Status: SKELETON. The data structures + interfaces are defined so the
// editor and the WASM bridge can compile against them. The actual meshing
// + streaming + threading are tracked as Tier 2.3 in
// docs/MODULARITY_ROADMAP.md.
//
// The skeleton is enough to support a single in-memory chunk that you can
// set/get blocks on, then render via MeshRenderer. The streaming + terrain
// generation + greedy meshing are the hard parts that come later.
// =============================================================================
#pragma once
